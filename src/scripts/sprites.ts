/** Draws a sprite into an offscreen canvas at an integer scale, with the given colours. */
export function rasterize(sprite: Sprite, scale: number, ink: string, accent: string): HTMLCanvasElement {
  const c = document.createElement('canvas');
  c.width = sprite.w * scale;
  c.height = sprite.h * scale;
  const ctx = c.getContext('2d')!;
  sprite.rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.' || ch === ' ') continue;
      ctx.fillStyle = ch === 'o' ? accent : ink;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  });
  return c;
}
